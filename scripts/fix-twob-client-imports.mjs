import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'

// Run after refreshing the checked-in Codama client. Keeping the address outside
// src/generated also keeps it outside the directory Codama clears when rendering.
const clientRoot = new URL('../src/lib/generated/twob/', import.meta.url)
const programFile = new URL('src/generated/programs/twobAnchor.ts', clientRoot)
const addressFile = new URL('program-address.ts', clientRoot)
const addressExport =
  "export { TWOB_ANCHOR_PROGRAM_ADDRESS } from '../../../program-address'"
const programSource = readFileSync(programFile, 'utf8')
const declaration = programSource.match(
  /export const TWOB_ANCHOR_PROGRAM_ADDRESS\s*=\s*['"][^'"]+['"]\s+as Address<['"][^'"]+['"]>;?/,
)

if (declaration) {
  writeFileSync(
    addressFile,
    '// Generated by pnpm twob:fix-imports from the checked-in Codama client.\n' +
      '// Keep this module free of runtime dependencies to avoid Metro require cycles.\n' +
      "import type { Address } from '@solana/kit'\n\n" +
      declaration[0] +
      '\n',
  )
  writeFileSync(
    programFile,
    programSource.replace(declaration[0], addressExport),
  )
} else if (!programSource.includes(addressExport) || !existsSync(addressFile)) {
  throw new Error(
    'Unrecognized TWOB program address export; check the Codama output.',
  )
}

let updatedImports = 0
for (const directory of ['instructions', 'errors']) {
  const directoryUrl = new URL(`src/generated/${directory}/`, clientRoot)
  for (const filename of readdirSync(directoryUrl)) {
    if (!filename.endsWith('.ts')) continue
    const file = new URL(filename, directoryUrl)
    const source = readFileSync(file, 'utf8')
    const updated = source.replace(
      /(import\s*\{\s*TWOB_ANCHOR_PROGRAM_ADDRESS\s*\}\s*from\s*['"])\.\.\/programs(['"])/g,
      '$1../../../program-address$2',
    )
    if (updated !== source) {
      writeFileSync(file, updated)
      updatedImports++
    }
  }
}

console.log(`TWOB program address isolated; updated ${updatedImports} imports.`)
